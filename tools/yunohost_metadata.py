#!/usr/bin/env python3
"""Genera la presentación del paquete a partir de sus metadatos y descripción."""
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def readme(root=ROOT):
    source = root / 'packaging/yunohost'
    manifest = tomllib.loads((source / 'manifest.toml').read_text())
    description = (source / 'doc/DESCRIPTION.md').read_text().strip()
    return f'''<!-- This README was automatically generated by tools/yunohost_metadata.py.
Structure follows https://github.com/YunoHost/apps_tools/tree/main/readme_generator.
Edit manifest.toml, doc/DESCRIPTION.md and doc/ADMIN.md; do not edit this file. -->

# {manifest['name']} for YunoHost

{manifest['description']['en']}

**Package version:** {manifest['version']} · **License:** {manifest['upstream']['license']}

{description}

## Install and upgrade

This package is maintained independently for installation from its repository
URL. It is not listed in the official catalog and no catalog inclusion is planned.

```bash
sudo yunohost app install https://github.com/Gente-del-Condado/headscale_gateway_ynh
sudo yunohost app upgrade headscale_gateway --url https://github.com/Gente-del-Condado/headscale_gateway_ynh
```

## Documentation and support

- [Installation, SSO, upgrade, backup and restoration](doc/ADMIN.md)
- [Complete web manual](https://gente-del-condado.github.io/headscale_gateway_ynh/)
- [Package issues](https://github.com/Gente-del-Condado/headscale_gateway_ynh/issues)
- [Maintenance and validation](doc/CATALOGO.md)

YunoHost downloads architecture-specific resources and complete corresponding
sources from a public release and verifies their SHA-256 checksums. Sources,
including Go dependencies and build instructions, are installed in
`sources/source.tar.gz`; third-party notices are in `doc/third_party/` in this
repository and `notices/` in the installation. Other platforms use the manual.

## En español

{manifest['description']['es']}. Consulta [la guía de administración](doc/ADMIN.md)
y el [manual web](https://gente-del-condado.github.io/headscale_gateway_ynh/).
'''


if __name__ == '__main__':
    (ROOT / 'packaging/yunohost/README.md').write_text(readme())
